/**
 * Find PIN code mapping with fallback to closest entry
 */
export function findPinCodeMapping(pinCode: string): PinCodeMapping | null {
  const cleanPin = pinCode.trim().replace(/\s+/g, '');
  if (PINCODE_DIRECTORY[cleanPin]) {
    return PINCODE_DIRECTORY[cleanPin];
  }

  // Prefix match (e.g. 462xxx for Bhopal region, 110xxx for Delhi, 221xxx for Varanasi)
  if (cleanPin.length >= 3) {
    const prefix = cleanPin.substring(0, 3);
    for (const [pin, data] of Object.entries(PINCODE_DIRECTORY)) {
      if (pin.startsWith(prefix)) {
        return {
          ...data,
          pinCode: cleanPin,
          postOfficeName: `${data.district} Area (${cleanPin})`,
        };
      }
    }
  }

  return null;
}
